@router.get("/breaches", response_model=list[BreachResponse])
async def list_breaches(
    zone_id: Optional[uuid.UUID] = None,
    resolved: Optional[bool] = None,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """List breach events with optional filters."""
    query = select(PerimeterBreach)
    if zone_id:
        query = query.where(PerimeterBreach.zone_id == zone_id)
    if resolved is True:
        query = query.where(PerimeterBreach.resolved_at.isnot(None))
    elif resolved is False:
        query = query.where(PerimeterBreach.resolved_at.is_(None))
    result = await db.execute(query.order_by(PerimeterBreach.detected_at.desc()))
    return result.scalars().all()


@router.get("/breaches/active", response_model=list[BreachResponse])
async def active_breaches(
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Return all unresolved breach events."""
    result = await db.execute(
        select(PerimeterBreach)
        .where(PerimeterBreach.resolved_at.is_(None))
        .order_by(PerimeterBreach.detected_at.desc())
    )
    return result.scalars().all()


@router.patch("/breaches/{breach_id}/resolve", response_model=BreachResponse)
async def resolve_breach(
    breach_id: uuid.UUID,
    payload: BreachResolve,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Mark a breach as resolved."""
    breach = await db.get(PerimeterBreach, breach_id)
    if not breach:
        raise HTTPException(status_code=404, detail="Breach not found")
    if breach.resolved_at:
        raise HTTPException(status_code=409, detail="Breach already resolved")
    breach.resolved_at = datetime.now(timezone.utc)
    breach.resolved_by = str(current_user.id)
    breach.resolution_notes = payload.resolution_notes
    await db.commit()
    await db.refresh(breach)
    logger.info(f"Breach {breach_id} resolved by {str(current_user.id)}")
    return breach


