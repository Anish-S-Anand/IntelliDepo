"""
Intelli Depot — Perimeter Monitoring
Feature: DEPOT-V7

Zone-based perimeter breach detection, unauthorized-access alerts, and
incident tracking. Integrates with camera feeds (DEPOT-V1).

Dependency note: AUTH-6.2 (RBAC) is active.
Permission checks now use the shared RBAC dependency layer.

Detection note: Real motion/object detection triggering requires DEPOT-V2.
This module exposes a `POST /breaches` endpoint that accepts breach events
(generated by the detection pipeline or a hardware sensor) and a
`POST /breaches/simulate` helper for testing without live camera feeds.
"""
import uuid
import logging
from datetime import datetime, timezone
from enum import Enum
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, ConfigDict, Field
from sqlalchemy import Column, String, Integer, Float, Boolean, DateTime, Text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy import select

from app.database import BaseModel as DBBaseModel, get_db
from app.core.auth.dependencies import get_current_user, require_permission
from app.core.redis_client import get_redis
from app.core.notifications.service_compat import NotificationService
from app.shared.models.user import User
