logger = logging.getLogger("intelli.depot.perimeter")

router = APIRouter(prefix="/depot/vision/perimeter", tags=["Depot - Perimeter"])




# ---------------------------------------------------------------------------
# Enums
# ---------------------------------------------------------------------------

class ZoneType(str, Enum):
    RESTRICTED = "restricted"       # no-entry at all times
    CONTROLLED = "controlled"       # entry allowed with authorisation
    HAZARDOUS = "hazardous"         # PPE or safety clearance required
    LOADING = "loading"             # dock / vehicle zone
    GENERAL = "general"             # monitored but unrestricted


class BreachType(str, Enum):
    UNAUTHORIZED_ENTRY = "unauthorized_entry"
    LOITERING = "loitering"
    FORCED_ENTRY = "forced_entry"
    AFTER_HOURS = "after_hours"
    OBJECT_LEFT = "object_left"
    UNKNOWN = "unknown"


class AlertSeverity(str, Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


# ---------------------------------------------------------------------------
# Database Models
# ---------------------------------------------------------------------------

class PerimeterZone(DBBaseModel):
    """A monitored perimeter zone associated with one or more cameras."""
    __tablename__ = "depot_perimeter_zones"

    name = Column(String, nullable=False)
    description = Column(Text, nullable=True)
    zone_type = Column(String, default=ZoneType.RESTRICTED)
    camera_id = Column(UUID(as_uuid=True), nullable=True, index=True)
    # polygon stored as JSON string: "[[x1,y1],[x2,y2],...]" (normalised 0-1)
    polygon_points = Column(Text, nullable=True)
    alert_on_entry = Column(Boolean, default=True)
    alert_severity = Column(String, default=AlertSeverity.HIGH)
    night_vision_enabled = Column(Boolean, default=False)
    night_vision_mode = Column(String, default="auto")  # auto, ir, thermal, off
    active_hours_start = Column(String, nullable=True)  # e.g. "06:00"
    active_hours_end = Column(String, nullable=True)    # e.g. "22:00"
    is_active = Column(Boolean, default=True)
    created_by = Column(String, nullable=True)


class PerimeterBreach(DBBaseModel):
    """An immutable breach event record."""
    __tablename__ = "depot_perimeter_breaches"

    zone_id = Column(UUID(as_uuid=True), nullable=False, index=True)
    camera_id = Column(UUID(as_uuid=True), nullable=True, index=True)
    breach_type = Column(String, default=BreachType.UNAUTHORIZED_ENTRY)
    severity = Column(String, default=AlertSeverity.HIGH)
    confidence = Column(Float, nullable=True)
    snapshot_ref = Column(String, nullable=True)  # path/URL to frame snapshot
    alert_sent = Column(Boolean, default=False)
    notes = Column(Text, nullable=True)
    detected_at = Column(DateTime(timezone=True), nullable=False)
    resolved_at = Column(DateTime(timezone=True), nullable=True)
    resolved_by = Column(String, nullable=True)
    resolution_notes = Column(Text, nullable=True)


# ---------------------------------------------------------------------------
# Pydantic Schemas
# ---------------------------------------------------------------------------

class PerimeterZoneCreate(BaseModel):
    name: str = Field(..., json_schema_extra={"example": "Server Room Entrance"})
    description: Optional[str] = None
    zone_type: ZoneType = ZoneType.RESTRICTED
    camera_id: Optional[uuid.UUID] = None
    polygon_points: Optional[str] = Field(
        None,
        example="[[0.1,0.1],[0.9,0.1],[0.9,0.9],[0.1,0.9]]",
        description="JSON array of [x,y] pairs, coordinates normalised 0-1",
    )
    alert_on_entry: bool = True
    alert_severity: AlertSeverity = AlertSeverity.HIGH


class PerimeterZoneResponse(BaseModel):
    id: uuid.UUID
    name: str
    description: Optional[str]
    zone_type: str
    camera_id: Optional[uuid.UUID]
    polygon_points: Optional[str]
    alert_on_entry: bool
    alert_severity: str
    is_active: bool
    created_by: Optional[str]
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class BreachCreate(BaseModel):
    zone_id: uuid.UUID
    camera_id: Optional[uuid.UUID] = None
    breach_type: BreachType = BreachType.UNAUTHORIZED_ENTRY
    confidence: Optional[float] = Field(None, ge=0.0, le=1.0)
    snapshot_ref: Optional[str] = None
    notes: Optional[str] = None
    detected_at: Optional[datetime] = None


class BreachResponse(BaseModel):
    id: uuid.UUID
    zone_id: uuid.UUID
    camera_id: Optional[uuid.UUID]
    breach_type: str
    severity: str
    confidence: Optional[float]
    snapshot_ref: Optional[str]
    alert_sent: bool
    notes: Optional[str]
    detected_at: datetime
    resolved_at: Optional[datetime]
    resolved_by: Optional[str]
    resolution_notes: Optional[str]
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class BreachResolve(BaseModel):
    resolution_notes: Optional[str] = Field(None, json_schema_extra={"example": "Authorised maintenance team entry confirmed"})


class SimulateBreachRequest(BaseModel):
    zone_id: uuid.UUID
    breach_type: BreachType = BreachType.UNAUTHORIZED_ENTRY
    confidence: float = Field(0.87, ge=0.0, le=1.0)
    notes: Optional[str] = Field("Simulated breach for testing", json_schema_extra={"example": "Simulated breach for testing"})


# ---------------------------------------------------------------------------
# Helper
# ---------------------------------------------------------------------------

def _severity_for_zone(zone: PerimeterZone) -> str:
    """Derive breach severity from zone configuration."""
    return zone.alert_severity


