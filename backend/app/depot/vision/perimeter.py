@router.post("/zones", response_model=PerimeterZoneResponse, status_code=201)
async def create_zone(
    payload: PerimeterZoneCreate,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Register a new perimeter zone."""
    zone = PerimeterZone(**payload.model_dump(), created_by=str(current_user.id))
    db.add(zone)
    await db.commit()
    await db.refresh(zone)
    logger.info(f"Perimeter zone created: {zone.name} ({zone.zone_type})")
    return zone


@router.get("/zones", response_model=list[PerimeterZoneResponse])
async def list_zones(
    zone_type: Optional[ZoneType] = None,
    camera_id: Optional[uuid.UUID] = None,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """List active perimeter zones."""
    query = select(PerimeterZone).where(PerimeterZone.is_active == True)
    if zone_type:
        query = query.where(PerimeterZone.zone_type == zone_type)
    if camera_id:
        query = query.where(PerimeterZone.camera_id == camera_id)
    result = await db.execute(query)
    return result.scalars().all()


@router.get("/zones/{zone_id}", response_model=PerimeterZoneResponse)
async def get_zone(
    zone_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Get a specific perimeter zone."""
    zone = await db.get(PerimeterZone, zone_id)
    if not zone or not zone.is_active:
        raise HTTPException(status_code=404, detail="Perimeter zone not found")
    return zone


@router.patch("/zones/{zone_id}/deactivate", response_model=PerimeterZoneResponse)
async def deactivate_zone(
    zone_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Deactivate a perimeter zone (stops alerting)."""
    zone = await db.get(PerimeterZone, zone_id)
    if not zone:
        raise HTTPException(status_code=404, detail="Perimeter zone not found")
    zone.is_active = False
    await db.commit()
    await db.refresh(zone)
    logger.info(f"Perimeter zone deactivated: {zone.name}")
    return zone


