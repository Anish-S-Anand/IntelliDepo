# Security Breach Agent — autonomous breach detection & dispatch
# ---------------------------------------------------------------------------

class BreachAgentRequest(BaseModel):
    """Trigger the Security Breach Agent to scan all active zones."""
    camera_id: Optional[uuid.UUID] = None
    simulate_breach_count: int = Field(0, ge=0, le=10, description="Number of synthetic breaches to generate for testing")


class BreachAgentResult(BaseModel):
    zones_scanned: int
    breaches_detected: int
    alerts_dispatched: int
    breaches: list[BreachResponse]


@router.post("/agent/scan", response_model=BreachAgentResult, status_code=200)
async def run_security_breach_agent(
    payload: BreachAgentRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
    redis: aioredis.Redis = Depends(get_redis),
):
    """
    Security Breach Agent: autonomously scans all active perimeter zones,
    detects motion/intrusion events (simulated until real CV pipeline is wired),
    logs breach records, and dispatches alerts to the Notification Hub.

    Supports night vision zones — adjusts detection confidence for IR/thermal modes.
    """
    import random

    # Get all active zones, optionally filtered by camera
    query = select(PerimeterZone).where(PerimeterZone.is_active == True)
    if payload.camera_id:
        query = query.where(PerimeterZone.camera_id == payload.camera_id)
    result = await db.execute(query)
    zones = list(result.scalars().all())

    if not zones:
        raise HTTPException(status_code=404, detail="No active perimeter zones found")

    breaches_created: list[PerimeterBreach] = []
    alerts_dispatched = 0

    for zone in zones:
        # Simulate breach detection — replace with real motion detection pipeline
        # Night vision zones get slightly lower confidence in thermal/IR mode
        base_confidence = 0.92
        if zone.night_vision_enabled and zone.night_vision_mode in ("ir", "thermal"):
            base_confidence = 0.85

        # Determine if a breach is detected (simulated)
        breach_detected = (payload.simulate_breach_count > len(breaches_created))

        if not breach_detected:
            continue

        # Determine breach type based on zone type and time
        breach_type = BreachType.UNAUTHORIZED_ENTRY
        if zone.zone_type == ZoneType.RESTRICTED:
            breach_type = BreachType.UNAUTHORIZED_ENTRY
        elif zone.zone_type == ZoneType.HAZARDOUS:
            breach_type = BreachType.FORCED_ENTRY

        # Check if after hours
        current_hour = datetime.now(timezone.utc).hour
        if zone.active_hours_end:
            try:
                end_hour = int(zone.active_hours_end.split(":")[0])
                if current_hour >= end_hour or current_hour < 6:
                    breach_type = BreachType.AFTER_HOURS
            except ValueError:
                pass

        confidence = round(random.uniform(base_confidence - 0.05, base_confidence + 0.05), 4)
        severity = _severity_for_zone(zone)

        breach = PerimeterBreach(
            zone_id=zone.id,
            camera_id=zone.camera_id,
            breach_type=breach_type,
            severity=severity,
            confidence=confidence,
            snapshot_ref=f"agent://scan-{datetime.now(timezone.utc).isoformat()}",
            notes=f"Detected by Security Breach Agent. Night vision: {zone.night_vision_mode if zone.night_vision_enabled else 'off'}",
            detected_at=datetime.now(timezone.utc),
            alert_sent=True,
        )
        db.add(breach)
        breaches_created.append(breach)

        # Dispatch to Notification Hub
        try:
            priority_map = {"low": "LOW", "medium": "NORMAL", "high": "HIGH", "critical": "CRITICAL"}
            await NotificationService.send_alert(
                db=db,
                redis=redis,
                user_id=current_user.id,
                event_type="depot.perimeter.breach",
                title=f"Security Breach — {zone.name}",
                message=f"{breach_type.value.replace('_', ' ').title()} detected in {zone.name} (confidence: {confidence:.0%})",
                priority=priority_map.get(severity, "HIGH"),
                payload={
                    "zone_name": zone.name,
                    "zone_type": zone.zone_type,
                    "breach_type": breach_type,
                    "confidence": confidence,
                    "night_vision": zone.night_vision_enabled,
                },
                channel="in_app",
            )
            alerts_dispatched += 1
        except Exception as e:
            logger.warning(f"Failed to dispatch breach alert for zone {zone.name}: {e}")

    await db.commit()
    for b in breaches_created:
        await db.refresh(b)

    logger.info(
        f"Security Breach Agent: scanned {len(zones)} zones, "
        f"detected {len(breaches_created)} breaches, dispatched {alerts_dispatched} alerts"
    )

    return BreachAgentResult(
        zones_scanned=len(zones),
        breaches_detected=len(breaches_created),
        alerts_dispatched=alerts_dispatched,
        breaches=[BreachResponse.model_validate(b) for b in breaches_created],
    )
