class NightVisionConfig(BaseModel):
    night_vision_enabled: bool = True
    night_vision_mode: str = Field("auto", description="auto, ir, thermal, off")
    active_hours_start: Optional[str] = Field(None, json_schema_extra={"example": "06:00"})
    active_hours_end: Optional[str] = Field(None, json_schema_extra={"example": "22:00"})


@router.patch("/zones/{zone_id}/night-vision", response_model=PerimeterZoneResponse)
async def configure_night_vision(
    zone_id: uuid.UUID,
    payload: NightVisionConfig,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Configure night vision mode for a perimeter zone.
    Modes: auto (switch IR on by light level), ir (always infrared),
    thermal (thermal imaging), off (disabled).
    Active hours define when standard vision is used vs. night vision.
    """
    zone = await db.get(PerimeterZone, zone_id)
    if not zone or not zone.is_active:
        raise HTTPException(status_code=404, detail="Zone not found")
    zone.night_vision_enabled = payload.night_vision_enabled
    zone.night_vision_mode = payload.night_vision_mode
    zone.active_hours_start = payload.active_hours_start
    zone.active_hours_end = payload.active_hours_end
    await db.commit()
    await db.refresh(zone)
    logger.info(f"Night vision configured for zone {zone.name}: mode={payload.night_vision_mode}")
    return zone


