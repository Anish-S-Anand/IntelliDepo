@router.post("/breaches", response_model=BreachResponse, status_code=201)
async def log_breach(
    payload: BreachCreate,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Log a perimeter breach event.
    Called by the detection pipeline (DEPOT-V2) or hardware sensors.
    """
    zone = await db.get(PerimeterZone, payload.zone_id)
    if not zone:
        raise HTTPException(status_code=404, detail="Perimeter zone not found")

    breach = PerimeterBreach(
        zone_id=payload.zone_id,
        camera_id=payload.camera_id or zone.camera_id,
        breach_type=payload.breach_type,
        severity=_severity_for_zone(zone),
        confidence=payload.confidence,
        snapshot_ref=payload.snapshot_ref,
        notes=payload.notes,
        detected_at=payload.detected_at or datetime.now(timezone.utc),
        alert_sent=zone.alert_on_entry,
    )
    db.add(breach)
    await db.commit()
    await db.refresh(breach)
    logger.warning(
        f"BREACH [{breach.severity.upper()}] zone={zone.name} "
        f"type={breach.breach_type} conf={breach.confidence}"
    )
    return breach


